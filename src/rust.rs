use anyhow::{Result, anyhow};

use std::fs;
use std::process::Command;

use crate::command_exists;

pub fn target_installed(target: &str) -> bool {
    let output = Command::new("rustup")
        .args(["target", "list", "--installed"])
        .output()
        .expect("failed to execute rustup");

    target_in_list(&String::from_utf8_lossy(&output.stdout), target)
}

fn target_in_list(installed: &str, target: &str) -> bool {
    installed.lines().any(|line| line.trim() == target)
}

pub fn check_rust() {
    println!("[Rust]");
    if command_exists("cargo") {
        println!("\x1b[32m[✓]\x1b[0m cargo is installed");
    } else {
        println!("\x1b[31m[✗]\x1b[0m cargo is not installed");
    };
}

const UNIFFI_GIT: &str = "https://github.com/mozilla/uniffi-rs";
// uniffi-bindgen-kotlin-jni is not published on crates.io, so pin all uniffi crates to the same commit
const UNIFFI_REV: &str = "c31f4bc025c7a31eae56b49107f50e6d38e76bc7";

pub fn create_rust(name: &str) {
    Command::new("cargo")
        .args(["new", &format!("{name}/{name}"), "--lib"])
        .status()
        .expect("failed to run cargo");

    fs::rename(format!("{name}/{name}"), format!("{name}/rust")).unwrap();

    // Library crate: JNI scaffolding is generated by build.rs and included in lib.rs
    let cargo_toml_path = format!("{name}/rust/Cargo.toml");
    let cargo_toml_content = lib_cargo_toml(name);
    fs::write(&cargo_toml_path, cargo_toml_content).expect("failed to write Cargo.toml");

    let build_rs_path = format!("{name}/rust/build.rs");
    let build_rs_content = "fn main() {\n    uniffi_bindgen_kotlin_jni::generate_scaffolding();\n}\n";
    fs::write(build_rs_path, build_rs_content).expect("failed to write build.rs");

    create_cargo_config(name).expect("failed to create cargo config");

    // Separate bindgen crate so its host-only dependencies don't get built for Android targets
    let bindgen_dir = format!("{name}/rust/uniffi-bindgen");
    fs::create_dir_all(format!("{bindgen_dir}/src")).expect("failed to create uniffi-bindgen dir");
    let bindgen_toml_content = bindgen_cargo_toml();
    fs::write(format!("{bindgen_dir}/Cargo.toml"), bindgen_toml_content)
        .expect("failed to write uniffi-bindgen Cargo.toml");
    let bindgen_rs_content = "fn main() -> uniffi_bindgen_kotlin_jni::Result<()> {\n    uniffi_bindgen_kotlin_jni::main()\n}\n";
    fs::write(format!("{bindgen_dir}/src/main.rs"), bindgen_rs_content)
        .expect("failed to write uniffi-bindgen main.rs");
}

fn lib_cargo_toml(name: &str) -> String {
    format!(
        r#"[package]
name = "{name}"
version = "0.1.0"
edition = "2024"

[lib]
crate-type = ["cdylib"]

[dependencies]
uniffi = {{ git = "{UNIFFI_GIT}", rev = "{UNIFFI_REV}", default-features = false }}
uniffi-bindgen-kotlin-jni-runtime = {{ git = "{UNIFFI_GIT}", rev = "{UNIFFI_REV}" }}

[build-dependencies]
uniffi-bindgen-kotlin-jni = {{ git = "{UNIFFI_GIT}", rev = "{UNIFFI_REV}" }}

[workspace]
members = ["uniffi-bindgen"]
"#
    )
}

fn bindgen_cargo_toml() -> String {
    format!(
        r#"[package]
name = "uniffi-bindgen"
version = "0.1.0"
edition = "2024"
publish = false

[dependencies]
uniffi-bindgen-kotlin-jni = {{ git = "{UNIFFI_GIT}", rev = "{UNIFFI_REV}" }}
"#
    )
}

fn cargo_config(ndk_root: &str) -> String {
    format!(
        r#"[target.aarch64-linux-android]
linker = "{ndk_root}/toolchains/llvm/prebuilt/darwin-x86_64/bin/aarch64-linux-android24-clang"

[target.armv7-linux-androideabi]
linker = "{ndk_root}/toolchains/llvm/prebuilt/darwin-x86_64/bin/armv7a-linux-androideabi24-clang"

[target.i686-linux-android]
linker = "{ndk_root}/toolchains/llvm/prebuilt/darwin-x86_64/bin/i686-linux-android24-clang"

[target.x86_64-linux-android]
linker = "{ndk_root}/toolchains/llvm/prebuilt/darwin-x86_64/bin/x86_64-linux-android24-clang"
"#
    )
}

fn create_cargo_config(name: &str) -> Result<()> {
    let cargo_dir = format!("./{name}/rust/.cargo");
    fs::create_dir_all(&cargo_dir)?;

    let config_path = format!("{cargo_dir}/config.toml");
    let ndk_root = std::env::var("ANDROID_NDK_HOME")
        .unwrap_or_else(|_| "/Users/charafau/Utils/android-sdk/ndk/30.0.14904198".to_string());

    let config_content = cargo_config(&ndk_root);

    fs::write(config_path, config_content)?;
    Ok(())
}

pub fn get_lib_name() -> Result<String> {
    let cargo_toml = fs::read_to_string("./rust/Cargo.toml")?;
    parse_lib_name(&cargo_toml)
}

fn parse_lib_name(cargo_toml: &str) -> Result<String> {
    cargo_toml
        .lines()
        .find_map(|line| {
            let line = line.trim();
            if line.starts_with("name =") || line.starts_with("name=") {
                line.split('=').nth(1).map(|s| s.trim().trim_matches('"'))
            } else {
                None
            }
        })
        .map(|name| name.replace('-', "_"))
        .ok_or_else(|| anyhow!("Could not find package name in Cargo.toml"))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_target_in_list() {
        let installed = "aarch64-apple-darwin\naarch64-linux-android\nx86_64-linux-android\n";
        assert!(target_in_list(installed, "aarch64-linux-android"));
        assert!(target_in_list(installed, "x86_64-linux-android"));
        assert!(!target_in_list(installed, "i686-linux-android"));
        // must match the whole line, not a prefix
        assert!(!target_in_list(installed, "aarch64-linux"));
        assert!(!target_in_list("", "aarch64-linux-android"));
    }

    #[test]
    fn test_parse_lib_name() {
        let cargo_toml = "[package]\nname = \"my-app\"\nversion = \"0.1.0\"\n";
        assert_eq!(parse_lib_name(cargo_toml).unwrap(), "my_app");
    }

    #[test]
    fn test_parse_lib_name_without_spaces() {
        let cargo_toml = "[package]\nname=\"demo\"\n";
        assert_eq!(parse_lib_name(cargo_toml).unwrap(), "demo");
    }

    #[test]
    fn test_parse_lib_name_missing() {
        assert!(parse_lib_name("[package]\nversion = \"0.1.0\"\n").is_err());
    }

    #[test]
    fn test_parse_lib_name_from_generated_cargo_toml() {
        assert_eq!(parse_lib_name(&lib_cargo_toml("hello-world")).unwrap(), "hello_world");
    }

    #[test]
    fn test_lib_cargo_toml() {
        let toml = lib_cargo_toml("demo");
        assert!(toml.contains("name = \"demo\""));
        assert!(toml.contains("crate-type = [\"cdylib\"]"));
        assert!(toml.contains("members = [\"uniffi-bindgen\"]"));
        assert!(toml.contains("default-features = false"));
        for dep in [
            "uniffi = ",
            "uniffi-bindgen-kotlin-jni-runtime = ",
            "uniffi-bindgen-kotlin-jni = ",
        ] {
            let line = toml.lines().find(|l| l.starts_with(dep)).unwrap();
            assert!(line.contains(UNIFFI_GIT), "{line}");
            assert!(line.contains(UNIFFI_REV), "{line}");
        }
        // bindgen is a build-dependency, runtime is a regular dependency
        let build_deps = toml.split("[build-dependencies]").nth(1).unwrap();
        assert!(build_deps.contains("uniffi-bindgen-kotlin-jni = "));
        assert!(!build_deps.contains("uniffi-bindgen-kotlin-jni-runtime"));
    }

    #[test]
    fn test_bindgen_cargo_toml() {
        let toml = bindgen_cargo_toml();
        assert!(toml.contains("name = \"uniffi-bindgen\""));
        assert!(toml.contains("publish = false"));
        assert!(toml.contains(&format!(
            "uniffi-bindgen-kotlin-jni = {{ git = \"{UNIFFI_GIT}\", rev = \"{UNIFFI_REV}\" }}"
        )));
    }

    #[test]
    fn test_cargo_config() {
        let config = cargo_config("/ndk");
        for (target, compiler) in [
            ("aarch64-linux-android", "aarch64-linux-android24-clang"),
            ("armv7-linux-androideabi", "armv7a-linux-androideabi24-clang"),
            ("i686-linux-android", "i686-linux-android24-clang"),
            ("x86_64-linux-android", "x86_64-linux-android24-clang"),
        ] {
            assert!(config.contains(&format!("[target.{target}]")), "{target}");
            assert!(config.contains(&format!(
                "linker = \"/ndk/toolchains/llvm/prebuilt/darwin-x86_64/bin/{compiler}\""
            )));
        }
    }
}
