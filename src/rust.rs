use anyhow::Result;

use std::fs;
use std::process::Command;

use crate::command_exists;

pub fn target_installed(target: &str) -> bool {
    let output = Command::new("rustup")
        .args(["target", "list", "--installed"])
        .output()
        .expect("failed to execute rustup");

    String::from_utf8_lossy(&output.stdout)
        .lines()
        .any(|line| line == target)
}

pub fn check_rust() {
    println!("[Rust]");
    if command_exists("cargo") {
        println!("\x1b[32m[✓]\x1b[0m cargo is installed");
    } else {
        println!("\x1b[31m[✗]\x1b[0m cargo is not installed");
    };
}

const UNIFFI_GIT: &str = "https://github.com/mozilla/uniffi-rs";
// uniffi-bindgen-kotlin-jni is not published on crates.io, so pin all uniffi crates to the same commit
const UNIFFI_REV: &str = "c31f4bc025c7a31eae56b49107f50e6d38e76bc7";

pub fn create_rust(name: &str) {
    Command::new("cargo")
        .args(["new", &format!("{name}/{name}"), "--lib"])
        .status()
        .expect("failed to run cargo");

    fs::rename(format!("{name}/{name}"), format!("{name}/rust")).unwrap();

    // Library crate: JNI scaffolding is generated by build.rs and included in lib.rs
    let cargo_toml_path = format!("{name}/rust/Cargo.toml");
    let cargo_toml_content = format!(
        r#"[package]
name = "{name}"
version = "0.1.0"
edition = "2024"

[lib]
crate-type = ["cdylib"]

[dependencies]
uniffi = {{ git = "{UNIFFI_GIT}", rev = "{UNIFFI_REV}", default-features = false }}
uniffi-bindgen-kotlin-jni-runtime = {{ git = "{UNIFFI_GIT}", rev = "{UNIFFI_REV}" }}

[build-dependencies]
uniffi-bindgen-kotlin-jni = {{ git = "{UNIFFI_GIT}", rev = "{UNIFFI_REV}" }}

[workspace]
members = ["uniffi-bindgen"]
"#
    );
    fs::write(&cargo_toml_path, cargo_toml_content).expect("failed to write Cargo.toml");

    let build_rs_path = format!("{name}/rust/build.rs");
    let build_rs_content = "fn main() {\n    uniffi_bindgen_kotlin_jni::generate_scaffolding();\n}\n";
    fs::write(build_rs_path, build_rs_content).expect("failed to write build.rs");

    create_cargo_config(name).expect("failed to create cargo config");

    // Separate bindgen crate so its host-only dependencies don't get built for Android targets
    let bindgen_dir = format!("{name}/rust/uniffi-bindgen");
    fs::create_dir_all(format!("{bindgen_dir}/src")).expect("failed to create uniffi-bindgen dir");
    let bindgen_toml_content = format!(
        r#"[package]
name = "uniffi-bindgen"
version = "0.1.0"
edition = "2024"
publish = false

[dependencies]
uniffi-bindgen-kotlin-jni = {{ git = "{UNIFFI_GIT}", rev = "{UNIFFI_REV}" }}
"#
    );
    fs::write(format!("{bindgen_dir}/Cargo.toml"), bindgen_toml_content)
        .expect("failed to write uniffi-bindgen Cargo.toml");
    let bindgen_rs_content = "fn main() -> uniffi_bindgen_kotlin_jni::Result<()> {\n    uniffi_bindgen_kotlin_jni::main()\n}\n";
    fs::write(format!("{bindgen_dir}/src/main.rs"), bindgen_rs_content)
        .expect("failed to write uniffi-bindgen main.rs");
}

fn create_cargo_config(name: &str) -> Result<()> {
    let cargo_dir = format!("./{name}/rust/.cargo");
    fs::create_dir_all(&cargo_dir)?;

    let config_path = format!("{cargo_dir}/config.toml");
    let ndk_root = std::env::var("ANDROID_NDK_HOME")
        .unwrap_or_else(|_| "/Users/charafau/Utils/android-sdk/ndk/30.0.14904198".to_string());

    let config_content = format!(
        r#"[target.aarch64-linux-android]
linker = "{ndk_root}/toolchains/llvm/prebuilt/darwin-x86_64/bin/aarch64-linux-android24-clang"

[target.armv7-linux-androideabi]
linker = "{ndk_root}/toolchains/llvm/prebuilt/darwin-x86_64/bin/armv7a-linux-androideabi24-clang"

[target.i686-linux-android]
linker = "{ndk_root}/toolchains/llvm/prebuilt/darwin-x86_64/bin/i686-linux-android24-clang"

[target.x86_64-linux-android]
linker = "{ndk_root}/toolchains/llvm/prebuilt/darwin-x86_64/bin/x86_64-linux-android24-clang"
"#
    );

    fs::write(config_path, config_content)?;
    Ok(())
}

pub fn get_lib_name() -> Result<String> {
    let cargo_toml = fs::read_to_string("./rust/Cargo.toml")?;
        let lib_name = cargo_toml
            .lines()
            .find_map(|line| {
                let line = line.trim();
                if line.starts_with("name =") || line.starts_with("name=") {
                    line.split('=').nth(1).map(|s| s.trim().trim_matches('"'))
                } else {
                    None
                }
            })
            .unwrap()
            .replace('-', "_");

    Ok(lib_name)
}
