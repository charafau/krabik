use anyhow::{Context, Result, anyhow};

use std::fs;
use std::path::Path;
use std::process::Command;

use crate::naming::ProjectName;
use crate::{check_mark, command_exists, run_command};

/// Checks whether a given Rustup compilation target is installed.
pub fn target_installed(target: &str) -> bool {
    Command::new("rustup")
        .args(["target", "list", "--installed"])
        .output()
        .map(|out| {
            out.status.success() && target_in_list(&String::from_utf8_lossy(&out.stdout), target)
        })
        .unwrap_or(false)
}

/// Checks whether a target matches any line in the `rustup target list --installed` output.
fn target_in_list(installed: &str, target: &str) -> bool {
    installed.lines().any(|line| line.trim() == target)
}

/// Doctor check verifying whether the Rust toolchain (cargo) is installed.
pub fn check_rust() -> bool {
    println!("[Rust]");
    let cargo_installed = command_exists("cargo");
    if cargo_installed {
        println!("{} cargo is installed", check_mark(true));
    } else {
        println!("{} cargo is not installed", check_mark(false));
    }
    cargo_installed
}

const UNIFFI_GIT: &str = "https://github.com/mozilla/uniffi-rs";
// uniffi-bindgen-kotlin-jni is not published on crates.io, so pin all uniffi crates to the same commit
const UNIFFI_REV: &str = "c31f4bc025c7a31eae56b49107f50e6d38e76bc7";

/// Creates the Rust library crate and UniFFI binding crates for the project.
pub fn create_rust(name: &ProjectName, root: &Path) -> Result<()> {
    let rust_dir = root.join("rust");

    // `--vcs none` keeps the crate from becoming a repository of its own: the
    // generated project is a single repository.
    let mut cmd = Command::new("cargo");
    cmd.arg("new")
        .arg(&rust_dir)
        .arg("--lib")
        .arg("--name")
        .arg(name.package_name())
        .arg("--vcs")
        .arg("none");
    run_command(&mut cmd, "cargo new")?;

    // cargo only writes this for VCS backed projects
    fs::write(rust_dir.join(".gitignore"), "/target\n")
        .with_context(|| format!("failed to write {}/.gitignore", rust_dir.display()))?;

    // Library crate: JNI scaffolding is generated by build.rs and included in lib.rs
    let cargo_toml_path = rust_dir.join("Cargo.toml");
    let cargo_toml_content = lib_cargo_toml(name.package_name());
    fs::write(&cargo_toml_path, cargo_toml_content)
        .with_context(|| format!("failed to write {}", cargo_toml_path.display()))?;

    let build_rs_path = rust_dir.join("build.rs");
    let build_rs_content =
        "fn main() {\n    uniffi_bindgen_kotlin_jni::generate_scaffolding();\n}\n";
    fs::write(&build_rs_path, build_rs_content)
        .with_context(|| format!("failed to write {}", build_rs_path.display()))?;

    // Separate bindgen crate so its host-only dependencies don't get built for Android targets
    let bindgen_dir = rust_dir.join("uniffi-bindgen");
    fs::create_dir_all(bindgen_dir.join("src"))
        .with_context(|| format!("failed to create {}/src", bindgen_dir.display()))?;
    let bindgen_toml_content = bindgen_cargo_toml();
    fs::write(bindgen_dir.join("Cargo.toml"), bindgen_toml_content)
        .with_context(|| format!("failed to write {}/Cargo.toml", bindgen_dir.display()))?;
    let bindgen_rs_content = "fn main() -> uniffi_bindgen_kotlin_jni::Result<()> {\n    uniffi_bindgen_kotlin_jni::main()\n}\n";
    fs::write(bindgen_dir.join("src/main.rs"), bindgen_rs_content)
        .with_context(|| format!("failed to write {}/src/main.rs", bindgen_dir.display()))?;

    // Separate bindgen crate for Swift bindings (uses the standard UniFFI generator)
    let swift_bindgen_dir = rust_dir.join("uniffi-bindgen-swift");
    fs::create_dir_all(swift_bindgen_dir.join("src"))
        .with_context(|| format!("failed to create {}/src", swift_bindgen_dir.display()))?;
    fs::write(
        swift_bindgen_dir.join("Cargo.toml"),
        bindgen_swift_cargo_toml(),
    )
    .with_context(|| format!("failed to write {}/Cargo.toml", swift_bindgen_dir.display()))?;
    let swift_bindgen_rs_content = "fn main() {\n    uniffi::uniffi_bindgen_swift()\n}\n";
    fs::write(
        swift_bindgen_dir.join("src/main.rs"),
        swift_bindgen_rs_content,
    )
    .with_context(|| {
        format!(
            "failed to write {}/src/main.rs",
            swift_bindgen_dir.display()
        )
    })?;

    Ok(())
}

/// Generates the `Cargo.toml` manifest content for the core Rust shared library.
fn lib_cargo_toml(package_name: &str) -> String {
    format!(
        r#"[package]
name = "{package_name}"
version = "0.1.0"
edition = "2024"

[lib]
crate-type = ["cdylib", "staticlib"]

# macro-scaffolding is required by the standard Swift bindings generator. It is opt-in so it
# doesn't clash with the JNI scaffolding used by Android.
[features]
default = []
ios = ["uniffi/macro-scaffolding"]

[dependencies]
uniffi = {{ git = "{UNIFFI_GIT}", rev = "{UNIFFI_REV}", default-features = false }}
uniffi-bindgen-kotlin-jni-runtime = {{ git = "{UNIFFI_GIT}", rev = "{UNIFFI_REV}" }}

[build-dependencies]
uniffi-bindgen-kotlin-jni = {{ git = "{UNIFFI_GIT}", rev = "{UNIFFI_REV}" }}

[workspace]
members = ["uniffi-bindgen", "uniffi-bindgen-swift"]
"#
    )
}

/// Generates the `Cargo.toml` manifest for the Kotlin UniFFI bindgen binary crate.
fn bindgen_cargo_toml() -> String {
    format!(
        r#"[package]
name = "uniffi-bindgen"
version = "0.1.0"
edition = "2024"
publish = false

[dependencies]
uniffi-bindgen-kotlin-jni = {{ git = "{UNIFFI_GIT}", rev = "{UNIFFI_REV}" }}
"#
    )
}

/// Generates the `Cargo.toml` manifest for the Swift UniFFI bindgen binary crate.
fn bindgen_swift_cargo_toml() -> String {
    format!(
        r#"[package]
name = "uniffi-bindgen-swift"
version = "0.1.0"
edition = "2024"
publish = false

[dependencies]
uniffi = {{ git = "{UNIFFI_GIT}", rev = "{UNIFFI_REV}", default-features = false, features = ["cli", "cargo-metadata"] }}
"#
    )
}

/// Reads `./rust/Cargo.toml` and returns the sanitized Rust library name.
pub fn get_lib_name() -> Result<String> {
    let cargo_toml =
        fs::read_to_string("./rust/Cargo.toml").context("failed to read ./rust/Cargo.toml")?;
    parse_lib_name(&cargo_toml)
}

/// Parses the package name from a `Cargo.toml` string and converts hyphens to underscores.
fn parse_lib_name(cargo_toml: &str) -> Result<String> {
    cargo_toml
        .lines()
        .find_map(|line| {
            let line = line.trim();
            if line.starts_with("name =") || line.starts_with("name=") {
                line.split('=').nth(1).map(|s| s.trim().trim_matches('"'))
            } else {
                None
            }
        })
        .map(|name| name.replace('-', "_"))
        .ok_or_else(|| anyhow!("Could not find package name in Cargo.toml"))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_target_in_list() {
        let installed = "aarch64-apple-darwin\naarch64-linux-android\nx86_64-linux-android\n";
        assert!(target_in_list(installed, "aarch64-linux-android"));
        assert!(target_in_list(installed, "x86_64-linux-android"));
        assert!(!target_in_list(installed, "i686-linux-android"));
        // must match the whole line, not a prefix
        assert!(!target_in_list(installed, "aarch64-linux"));
        assert!(!target_in_list("", "aarch64-linux-android"));
    }

    #[test]
    fn test_parse_lib_name() {
        let cargo_toml = "[package]\nname = \"my-app\"\nversion = \"0.1.0\"\n";
        assert_eq!(parse_lib_name(cargo_toml).unwrap(), "my_app");
    }

    #[test]
    fn test_parse_lib_name_without_spaces() {
        let cargo_toml = "[package]\nname=\"demo\"\n";
        assert_eq!(parse_lib_name(cargo_toml).unwrap(), "demo");
    }

    #[test]
    fn test_parse_lib_name_missing() {
        assert!(parse_lib_name("[package]\nversion = \"0.1.0\"\n").is_err());
    }

    #[test]
    fn test_parse_lib_name_from_generated_cargo_toml() {
        assert_eq!(
            parse_lib_name(&lib_cargo_toml("hello-world")).unwrap(),
            "hello_world"
        );
    }

    #[test]
    fn test_lib_cargo_toml() {
        let toml = lib_cargo_toml("demo");
        assert!(toml.contains("name = \"demo\""));
        assert!(toml.contains("crate-type = [\"cdylib\", \"staticlib\"]"));
        assert!(toml.contains("members = [\"uniffi-bindgen\", \"uniffi-bindgen-swift\"]"));
        assert!(toml.contains("default-features = false"));
        assert!(toml.contains("ios = [\"uniffi/macro-scaffolding\"]"));
        for dep in [
            "uniffi = ",
            "uniffi-bindgen-kotlin-jni-runtime = ",
            "uniffi-bindgen-kotlin-jni = ",
        ] {
            let line = toml.lines().find(|l| l.starts_with(dep)).unwrap();
            assert!(line.contains(UNIFFI_GIT), "{line}");
            assert!(line.contains(UNIFFI_REV), "{line}");
        }
        // bindgen is a build-dependency, runtime is a regular dependency
        let build_deps = toml.split("[build-dependencies]").nth(1).unwrap();
        assert!(build_deps.contains("uniffi-bindgen-kotlin-jni = "));
        assert!(!build_deps.contains("uniffi-bindgen-kotlin-jni-runtime"));
    }

    #[test]
    fn test_lib_cargo_toml_keeps_hyphenated_package_name() {
        // Cargo package names may contain hyphens, the lib name is derived from them.
        let toml = lib_cargo_toml("my-app");
        assert!(toml.contains("name = \"my-app\""));
        assert_eq!(parse_lib_name(&toml).unwrap(), "my_app");
    }

    #[test]
    fn test_bindgen_cargo_toml() {
        let toml = bindgen_cargo_toml();
        assert!(toml.contains("name = \"uniffi-bindgen\""));
        assert!(toml.contains("publish = false"));
        assert!(toml.contains(&format!(
            "uniffi-bindgen-kotlin-jni = {{ git = \"{UNIFFI_GIT}\", rev = \"{UNIFFI_REV}\" }}"
        )));
    }

    #[test]
    fn test_bindgen_swift_cargo_toml() {
        let toml = bindgen_swift_cargo_toml();
        assert!(toml.contains("name = \"uniffi-bindgen-swift\""));
        assert!(toml.contains("publish = false"));
        assert!(toml.contains(&format!(
            "uniffi = {{ git = \"{UNIFFI_GIT}\", rev = \"{UNIFFI_REV}\", default-features = false, features = [\"cli\", \"cargo-metadata\"] }}"
        )));
    }
}
